#!/usr/bin/env bash
#
# gsr-config.sh — choisir et tester le micro utilisé par gsr-toggle.sh.
# Écrit la config dans ~/.config/gsr-toggle.conf (lue par gsr-toggle.sh).
#
# Les chaînes affichées passent par msg() / say() (voir lazycam-lang.sh) :
# anglais par défaut, français si la config ou la locale le demande.
#
set -u

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$DIR/lazycam-lang.sh"

CONF="${XDG_CONFIG_HOME:-$HOME/.config}/gsr-toggle.conf"
mkdir -p "$(dirname "$CONF")"

# valeurs par défaut, surchargées par la config existante
MIC=""
DENOISE=0
[ -f "$CONF" ] && . "$CONF"

for dep in pw-dump jq pw-record pw-play ffmpeg; do
    command -v "$dep" >/dev/null || {
        printf '%s %s\n' "$(msg 'Missing dependency:' 'Dépendance manquante :')" "$dep" >&2
        exit 1
    }
done

# --- liste des micros réels (Audio/Source, pas les monitors) -------------
load_mics() {
    NAMES=(); DESCS=()
    while IFS=$'\t' read -r name desc; do
        [ -z "$name" ] && continue
        NAMES+=("$name"); DESCS+=("$desc")
    done < <(pw-dump 2>/dev/null | jq -r --arg fallback "$(msg 'microphone' 'micro')" '
        .[] | select(.info.props["media.class"]=="Audio/Source")
        | "\(.info.props["node.name"])\t\(.info.props["node.description"] // .info.props["node.nick"] // $fallback)"')
}

current_label() {
    [ -z "$MIC" ] && { msg '(system default microphone)' '(micro par défaut du système)'; echo; return; }
    local i
    for i in "${!NAMES[@]}"; do
        [ "${NAMES[$i]}" = "$MIC" ] && { echo "${DESCS[$i]}"; return; }
    done
    echo "$MIC"
}

# --- test : enregistre 4 s, mesure le niveau, réécoute -------------------
test_mic() {
    local target="$1" tmp
    tmp="$(mktemp --suffix=.flac)"
    echo
    say '🎙  Recording 4 s — SPEAK NORMALLY now…' \
        '🎙  Enregistrement 4 s — PARLE NORMALEMENT maintenant…'
    if [ -n "$target" ]; then
        timeout 4 pw-record --target "$target" "$tmp" 2>/dev/null
    else
        timeout 4 pw-record "$tmp" 2>/dev/null
    fi
    local mean max
    mean="$(ffmpeg -hide_banner -i "$tmp" -af volumedetect -f null /dev/null 2>&1 | grep mean_volume | sed 's/.*: //')"
    max="$(ffmpeg -hide_banner -i "$tmp" -af volumedetect -f null /dev/null 2>&1 | grep max_volume | sed 's/.*: //')"
    printf '   %s %s   |   %s %s\n' \
        "$(msg 'Mean level:' 'Niveau moyen :')" "${mean:-?}" \
        "$(msg 'peak:' 'crête :')" "${max:-?}"
    say '   (rule of thumb: a decent voice averages ≈ -25 to -15 dB; the lower the background noise, the better)' \
        '   (repère : voix correcte ≈ -25 à -15 dB de moyenne ; bruit de fond plus bas = mieux)'
    say '▶  Playing the test back…' '▶  Réécoute du test…'
    pw-play "$tmp" 2>/dev/null
    rm -f "$tmp"
    echo
}

# ------------------------------- menu ------------------------------------
CONTINUE_PROMPT="$(msg '  [Enter to continue]' '  [Entrée pour continuer]')"

while true; do
    load_mics
    clear
    echo "════════════════════════════════════════════════════════"
    say '  Microphone setup — gsr-toggle (screen recording)' \
        '  Configuration micro — gsr-toggle (enregistrement écran)'
    echo "════════════════════════════════════════════════════════"
    printf '  %s %s\n' "$(msg 'Current microphone :' 'Micro actuel    :')" "$(current_label)"
    printf '  %s %s\n' "$(msg 'Noise reduction    :' 'Réduction bruit :')" \
        "$([ "${DENOISE:-0}" = 1 ] && msg 'ENABLED' 'ACTIVÉE' || msg 'disabled' 'désactivée')"
    echo "────────────────────────────────────────────────────────"
    say '  Available microphones:' '  Micros disponibles :'
    for i in "${!NAMES[@]}"; do
        mark="  "; [ "${NAMES[$i]}" = "$MIC" ] && mark="→ "
        printf "   %s%d) %s\n" "$mark" "$((i+1))" "${DESCS[$i]}"
    done
    echo
    say '   0) System default microphone'          '   0) Micro par défaut du système'
    say '   t) Test the currently selected mic'    '   t) Tester le micro actuellement sélectionné'
    say '   d) Toggle noise reduction'             '   d) Activer / désactiver la réduction de bruit'
    say '   s) Save and quit'                      '   s) Sauvegarder et quitter'
    say '   q) Quit without saving'                '   q) Quitter sans sauvegarder'
    echo "────────────────────────────────────────────────────────"
    read -rp "$(msg '  Choice (a number selects and tests): ' \
                    '  Choix (un numéro pour sélectionner + tester) : ')" choice

    case "$choice" in
        0) MIC=""; test_mic "" ; read -rp "$CONTINUE_PROMPT" _ ;;
        t|T) test_mic "$MIC" ; read -rp "$CONTINUE_PROMPT" _ ;;
        d|D) DENOISE=$([ "${DENOISE:-0}" = 1 ] && echo 0 || echo 1) ;;
        s|S)
            printf '# Generated by gsr-config.sh\nMIC=%q\nDENOISE=%q\n' "$MIC" "$DENOISE" > "$CONF"
            echo
            printf '%s %s\n' "$(msg '✓ Config saved to' '✓ Config enregistrée dans')" "$CONF"
            printf '  %s %s | %s %s\n' \
                "$(msg 'Microphone:' 'Micro :')" "$(current_label)" \
                "$(msg 'Noise:' 'Bruit :')" "$([ "$DENOISE" = 1 ] && echo ON || echo OFF)"
            exit 0 ;;
        q|Q) say 'Quit without saving.' 'Quitté sans sauvegarder.'; exit 0 ;;
        ''|*[!0-9]*) ;;  # ignore
        *)
            idx=$((choice-1))
            if [ "$idx" -ge 0 ] && [ "$idx" -lt "${#NAMES[@]}" ]; then
                MIC="${NAMES[$idx]}"
                test_mic "$MIC"
                read -rp "$CONTINUE_PROMPT" _
            fi ;;
    esac
done
